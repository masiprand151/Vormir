function IconItem({ name }: { name: string }) {
  return Stack({
    orientation: "vertical",
    spacing: 8,
    width: 90,
    padding: 8,
    children: [
      Icon({
        name: name as any,
        size: 28,
        color: "#2563eb",
      }),
      Text({
        text: name,
        fontSize: 11,
      }),
    ],
  });
}

function IconSection({ title, icons }: { title: string; icons: string[] }) {
  return Stack({
    orientation: "vertical",
    spacing: 12,
    children: [
      Text({
        text: title,
        fontSize: 18,
        fontWeight: "bold",
      }),

      Stack({
        orientation: "horizontal",
        spacing: 8,
        children: icons.map((name) => IconItem({ name })),
      }),

      Divider({
        color: "#dddddd",
        thickness: 1,
      }),
    ],
  });
}

